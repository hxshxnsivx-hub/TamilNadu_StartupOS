/* Keep <html lang> in step with the active language.
 *
 * This was never set, so the document stayed lang="en" no matter what the
 * switch said. Three things silently depended on it and all three were broken:
 *
 *   · every `:lang(ta)` / `:lang(hi)` rule — including the Tamil type metrics
 *     and the script-specific display sizing, which meant Tamil headings were
 *     being set with Latin measurements and clipped
 *   · the drop cap's script exclusion, which is what stops a floated initial
 *     slicing Tamil and Devanagari matras
 *   · screen-reader pronunciation, which picks the voice from the lang tag
 *
 * A language switch that does not change the document language is a label,
 * not a translation.
 */
const applyLang = (lng: string) => {
  const base = (lng || "en").split("-")[0];
  document.documentElement.lang = base;
};

applyLang(i18n.language);
i18n.on("languageChanged", applyLang);

